import { FlaskConical, Radio, History, Repeat, Sparkles, Sigma, type LucideIcon } from 'lucide-react'
import { cn } from '@/lib/cn'
import { Tooltip } from './Tooltip'

/**
 * Provenance is a first-class concept in SHARROW: every meaningful number
 * must disclose where it came from. These labels are never decorative.
 */
export type ProvenanceKind = 'simulated' | 'live' | 'historical' | 'backtest' | 'derived' | 'ai'

const CONFIG: Record<ProvenanceKind, { label: string; icon: LucideIcon; explain: string; className: string }> = {
  simulated: {
    label: 'SIMULATED',
    icon: FlaskConical,
    explain:
      'Generated by the SHARROW simulated market provider. These are not real market prices.',
    className: 'border-warn/30 bg-warn-soft text-warn',
  },
  live: {
    label: 'LIVE',
    icon: Radio,
    explain: 'Streamed from a connected live market data provider.',
    className: 'border-pos/30 bg-pos-soft text-pos',
  },
  historical: {
    label: 'HISTORICAL',
    icon: History,
    explain: 'Recorded historical dataset with a fixed observation window.',
    className: 'border-line-strong bg-surface-3 text-ink-2',
  },
  backtest: {
    label: 'BACKTESTED',
    icon: Repeat,
    explain: 'Result of running a rule over past data. Past behaviour does not guarantee future results.',
    className: 'border-accent-2/30 bg-accent-soft-2 text-accent-2',
  },
  derived: {
    label: 'DERIVED',
    icon: Sigma,
    explain: 'Computed by SHARROW from the underlying dataset. See sources for inputs.',
    className: 'border-line-strong bg-surface-3 text-ink-2',
  },
  ai: {
    label: 'AI INTERPRETATION',
    icon: Sparkles,
    explain: 'Generated interpretation from the SHARROW intelligence engine — not a guarantee of outcomes.',
    className: 'border-accent/30 bg-accent-soft text-accent',
  },
}

interface ProvenanceBadgeProps {
  kind: ProvenanceKind
  /** Show the full word; otherwise only the icon + tooltip. */
  compact?: boolean
  /** Hide the tooltip (when the surrounding copy already explains). */
  bare?: boolean
  className?: string
}

export function ProvenanceBadge({ kind, compact = false, bare = false, className }: ProvenanceBadgeProps) {
  const cfg = CONFIG[kind]
  const Icon = cfg.icon

  const node = (
    <span
      className={cn(
        'inline-flex h-5 items-center gap-1 rounded-full border px-1.5 font-mono text-2xs tracking-[0.04em]',
        cfg.className,
        className,
      )}
    >
      <Icon className="size-3" aria-hidden="true" strokeWidth={2} />
      {compact ? <span className="sr-only">{cfg.label}</span> : cfg.label}
    </span>
  )

  if (bare) return node
  return <Tooltip label={cfg.explain}>{node}</Tooltip>
}
